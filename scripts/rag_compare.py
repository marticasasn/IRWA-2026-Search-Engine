"""Runs the baseline (template) and the improved RAG generators on the same searches and writes
docs/rag_comparison.md with the query, the retrieved products and both answers side by side.

The answers are only shown, not scored. Needs GROQ_API_KEY (and GROQ_MODEL) in .env.
Run from the repository root: python scripts/rag_compare.py
"""

import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from dotenv import load_dotenv  # noqa: E402

load_dotenv(os.path.join(ROOT, ".env"))

from myapp.generation.rag import RAGGenerator  # noqa: E402
from myapp.generation.rag_improved import ImprovedRAGGenerator  # noqa: E402
from src.engine import SearchEngine  # noqa: E402

TEST_QUERIES = ["women cotton kurta", "men slim fit chinos", "hooded full sleeve sweatshirt",
                "blue denim shorts", "women black leggings"]
HARD_QUERIES = {
    "something nice to wear": "vague query",
    "laptop charger": "no good match in the corpus",
    "cheap black tshirt under 300": "price constraint",
}
METHOD = "custom"
SHOWN_PRODUCTS = 8      # retrieved products listed in the report
PAUSE_SECONDS = 2       # between LLM calls, to stay under the API rate limit
OUTPUT_PATH = os.path.join(ROOT, "docs", "rag_comparison.md")


def cell(text):
    """Text that fits in one markdown table cell (pipes escaped, new lines as <br>)."""
    return (text or "").strip().replace("|", "\\|").replace("\r", "").replace("\n", "<br>")


def products_table(results):
    """Markdown table with the first SHOWN_PRODUCTS retrieved products."""
    lines = ["| rank | pid | title | brand | price | MRP | discount | rating | stock | score |",
             "|---:|---|---|---|---:|---:|---|---:|---|---:|"]
    for r in results[:SHOWN_PRODUCTS]:
        lines.append("| {} | {} | {} | {} | {} | {} | {} | {} | {} | {:.4f} |".format(
            r["rank"], r["pid"], cell(" ".join((r["title"] or "").split())), cell(r["brand"]),
            r["selling_price"] or "", r["actual_price"] or "", r["discount"] or "",
            r["average_rating"] or "", "out of stock" if r["out_of_stock"] else "in stock", r["score"]))
    return lines


def main():
    """Runs both generators on every query and writes the markdown report."""
    engine = SearchEngine()
    baseline, improved = RAGGenerator(), ImprovedRAGGenerator()
    queries = [(q, "test query") for q in TEST_QUERIES] + list(HARD_QUERIES.items())

    lines = ["# RAG comparison: baseline vs improved", "",
             f"Generated by `scripts/rag_compare.py` on {time.strftime('%Y-%m-%d %H:%M')}.",
             f"Model: `{os.environ.get('GROQ_MODEL', 'llama-3.1-8b-instant')}`. "
             f"Search: method `{METHOD}`, all web search options on, top 20.", "",
             "- Baseline: template `RAGGenerator` (top 20 results, pid + title, template prompt).",
             f"- Improved: `ImprovedRAGGenerator` with its defaults (max {improved.max_products} products, "
             f"relative threshold {improved.relative_threshold}, rich context, strict prompt, temperature 0, "
             "citation check, no-good handling).", ""]
    for query, kind in queries:
        print("Query:", query)
        info = engine.search_with_info(query, method=METHOD)
        results = info["results"]
        base_answer = baseline.generate_response(query, results)
        time.sleep(PAUSE_SECONDS)
        imp = improved.generate_response(query, results, fallback=info["fallback"])
        time.sleep(PAUSE_SECONDS)

        lines += [f"## {query}", "", f"Type: {kind}. Total matches: {info['total']}. "
                  f"OR fallback: {info['fallback']}. Query terms: {', '.join(info['query_terms']) or 'none'}.", ""]
        lines += (products_table(results) if results else ["(no products retrieved)"]) + [""]
        lines += ["| Baseline | Improved |", "|---|---|", f"| {cell(base_answer)} | {cell(imp['text'])} |", ""]
        lines += [f"Improved: status `{imp['status']}`, products given to the model: "
                  f"{', '.join(imp['products']) or 'none'}; cited: {', '.join(imp['cited']) or 'none'}; "
                  f"cited but not given: {', '.join(imp['invalid']) or 'none'}."]
        if imp.get("discarded_text"):
            lines += ["", f"Discarded improved answer: {cell(imp['discarded_text'])}"]
        lines.append("")

    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("Saved to", OUTPUT_PATH)


if __name__ == "__main__":
    main()
