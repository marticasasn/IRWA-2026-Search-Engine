"""Writes docs/part4_search_before_after.md: top-5 titles of the 5 test queries with the web search
improvements switched off (before) and on (after), for the three ranking methods.

Run from the repository root: python scripts/search_before_after.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.engine import METHODS, ROOT_DIR, SearchEngine  # noqa: E402

TEST_QUERIES = ["women cotton kurta", "men slim fit chinos", "hooded full sleeve sweatshirt",
                "blue denim shorts", "women black leggings"]
TOP_N = 5
BEFORE = dict(protected_words=False, field_boost=False, or_fallback=False, collapse_duplicates=False)
AFTER = dict(protected_words=True, field_boost=True, or_fallback=True, collapse_duplicates=True)
OUTPUT_PATH = os.path.join(ROOT_DIR, "docs", "part4_search_before_after.md")


def format_list(info):
    """Markdown lines for one result list: a summary line and the numbered top titles."""
    lines = [f"total matches: {info['total']} | OR fallback: {info['fallback']} | "
             f"near-duplicates hidden: {info['hidden']}", ""]
    if not info["results"]:
        lines.append("(no results)")
    for r in info["results"]:
        title = " ".join((r["title"] or "").split())  # collapse non-breaking and repeated spaces
        lines.append(f"{r['rank']}. {title} ({r['brand'] or 'no brand'}, pid {r['pid']})")
    return lines


def main():
    """Runs every test query with every method before and after, and writes the markdown file."""
    engine = SearchEngine()
    lines = ["# Part 4: search results before / after the web improvements", "",
             f"Top {TOP_N} results of the test queries. Generated by `scripts/search_before_after.py`.", "",
             f"- before: `{BEFORE}` (same as `search_ranked` on the Part 1 index)",
             f"- after: `{AFTER}`", ""]
    for query in TEST_QUERIES:
        lines += [f"## {query}", ""]
        for method in METHODS:
            for label, options in (("before", BEFORE), ("after", AFTER)):
                info = engine.search_with_info(query, method=method, top_k=TOP_N, **options)
                lines += [f"### {method} - {label}", ""] + format_list(info) + [""]
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("Saved to", OUTPUT_PATH)


if __name__ == "__main__":
    main()
